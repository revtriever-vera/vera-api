import { AiSummary } from './summary.types';

const AUTO_GENERATION_INTERVAL_MS: number = 3_600_000;

export type CacheDecision = 'hit' | 'stale' | 'generate';

export function cacheDecisionOf(stored: AiSummary | null, contextHash: string, now: Date): CacheDecision {
    if (stored === null) {
        return 'generate';
    }
    if (stored.contextHash === contextHash) {
        return 'hit';
    }
    const last: Date | null = stored.lastAutoGeneratedAt;
    return last !== null && now.getTime() - last.getTime() < AUTO_GENERATION_INTERVAL_MS ? 'stale' : 'generate';
}
