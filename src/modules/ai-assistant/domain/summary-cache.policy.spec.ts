import { describe, expect, it } from 'vitest';
import { cacheDecisionOf } from './summary-cache.policy';
import { AiSummary } from './summary.types';

const NOW: Date = new Date('2026-11-23T12:00:00.000Z');

function stored(overrides: Partial<AiSummary> = {}): AiSummary {
    return {
        contextHash: 'hash-a',
        lastAutoGeneratedAt: new Date('2026-11-23T11:30:00.000Z'),
        ...overrides
    } as AiSummary;
}

describe('cacheDecisionOf', () => {
    it('sem texto guardado: gera', () => {
        expect(cacheDecisionOf(null, 'hash-a', NOW)).toBe('generate');
    });

    it('hash igual: devolve o guardado, mesmo se a última geração automática é antiga', () => {
        expect(cacheDecisionOf(stored(), 'hash-a', NOW)).toBe('hit');
        expect(cacheDecisionOf(stored({ lastAutoGeneratedAt: new Date('2026-11-01T00:00:00.000Z') }), 'hash-a', NOW)).toBe('hit');
    });

    it('hash diferente dentro da hora: guardado com stale', () => {
        expect(cacheDecisionOf(stored(), 'hash-b', NOW)).toBe('stale');
    });

    it('hash diferente fora da hora, no limite ou sem geração automática: gera', () => {
        expect(cacheDecisionOf(stored({ lastAutoGeneratedAt: new Date('2026-11-23T11:00:00.000Z') }), 'hash-b', NOW)).toBe('generate');
        expect(cacheDecisionOf(stored({ lastAutoGeneratedAt: new Date('2026-11-23T10:00:00.000Z') }), 'hash-b', NOW)).toBe('generate');
        expect(cacheDecisionOf(stored({ lastAutoGeneratedAt: null }), 'hash-b', NOW)).toBe('generate');
    });
});
