import { Injectable } from '@nestjs/common';
import { AppContext } from '../../../core/context/app-context.port';
import { DatabaseClient } from '../../../core/database/database.client';
import { TenantRepository } from '../../../core/database/repositories/tenant.repository';
import { IdUtil } from '../../../shared/utils/id.util';
import { AiSummary, SaveSummaryInput, SummaryKind } from '../domain/summary.types';

const PURGE_BATCH: number = 500;
const EXPORT_LIMIT: number = 2000;

interface StoredValues {
    readonly contextHash: string;
    readonly paragraphs: string;
    readonly source: string;
    readonly promptVersion: number;
    readonly llmCallId: string | null;
    readonly generatedAt: Date;
    readonly updatedAt: Date;
}

type AutoValues = { lastAutoGeneratedAt?: Date };

@Injectable()
export class AiSummariesRepository extends TenantRepository<'AiSummaries'> {
    public constructor(database: DatabaseClient, context: AppContext) {
        super(database, context, 'AiSummaries');
    }

    public async findStored(kind: SummaryKind, periodKey: string, locale: string): Promise<AiSummary | null> {
        return this.findOne({ kind, periodKey, locale });
    }

    public async save(input: SaveSummaryInput): Promise<AiSummary> {
        const now: Date = new Date();
        const stored: StoredValues = this.storedValuesOf(input, now);
        const auto: AutoValues = input.auto ? { lastAutoGeneratedAt: now } : {};
        return this.insertBuilder()
            .values({ ...this.keyOf(input), ...stored, ...auto })
            .onConflict((conflict) =>
                conflict
                    .columns(['companyId', 'kind', 'periodKey', 'locale'])
                    .where('deletedAt', 'is', null)
                    .doUpdateSet({ ...stored, ...auto })
            )
            .returningAll()
            .executeTakeFirstOrThrow();
    }

    public async listAll(): Promise<AiSummary[]> {
        return this.findMany({}, { limit: EXPORT_LIMIT, orderBy: [{ property: 'generatedAt', direction: 'desc' }] });
    }

    public async eraseAll(): Promise<number> {
        return this.hardDeleteWhere({}, PURGE_BATCH);
    }

    public async purgeBefore(cutoff: Date): Promise<number> {
        let purged: number = 0;
        let removed: number = await this.hardDeleteBefore('generatedAt', cutoff, PURGE_BATCH);
        while (removed > 0) {
            purged += removed;
            removed = await this.hardDeleteBefore('generatedAt', cutoff, PURGE_BATCH);
        }
        return purged;
    }

    private storedValuesOf(input: SaveSummaryInput, now: Date): StoredValues {
        return {
            contextHash: input.contextHash,
            paragraphs: JSON.stringify(input.paragraphs),
            source: 'model',
            promptVersion: input.promptVersion,
            llmCallId: input.llmCallId,
            generatedAt: now,
            updatedAt: now
        };
    }

    private keyOf(input: SaveSummaryInput): { id: string; companyId: string; kind: string; periodKey: string; locale: string } {
        return { id: IdUtil.newId(), companyId: this.companyId, kind: input.kind, periodKey: input.periodKey, locale: input.locale };
    }
}
