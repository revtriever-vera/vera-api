import { describe, expect, it, vi } from 'vitest';
import { LlmInvalidResponseError } from '../../../core/llm/llm.errors';
import { CapReachedError } from '../../../core/usage/usage.errors';
import { ReviewSource } from '../domain/context/ai-context.types';
import { AiSummary } from '../domain/summary.types';
import { AiSummaryDomain } from '../domain/ai-summary.domain';
import { AiAssistantMetricsService } from './ai-assistant-metrics.service';
import { AiConsentService } from './ai-consent.service';
import { AiContextBuilderService } from './ai-context-builder.service';
import { MonthlyReviewSummaryService } from './monthly-review-summary.service';
import { SummaryGeneratorService } from './summary-generator.service';
import { PlanGateService } from '../../plans/services/plan-gate.service';
import { AppContext } from '../../../core/context/app-context.port';

const REVIEW = { month: '2026-10' } as unknown as ReviewSource;
const BUILT = { payload: { mes: '2026-10' }, numbers: [], keys: new Map() };
const STORED = {
    contextHash: 'hash-1',
    paragraphs: ['Guardado.'],
    generatedAt: new Date('2026-11-01T05:00:00Z'),
    lastAutoGeneratedAt: null
} as unknown as AiSummary;

interface Options {
    readonly allowed?: boolean;
    readonly consent?: boolean;
    readonly stored?: AiSummary | null;
    readonly hash?: string;
    readonly generate?: () => Promise<unknown>;
}

function make(options: Options = {}) {
    const generate = vi.fn(
        options.generate ?? ((): Promise<unknown> => Promise.resolve({ paragraphs: ['Novo.'], callId: 'call-1', promptVersion: 1 }))
    );
    const save = vi.fn().mockResolvedValue({});
    const findStored = vi.fn().mockResolvedValue('stored' in options ? options.stored : null);
    const metrics = { summary: vi.fn() };
    const service: MonthlyReviewSummaryService = new MonthlyReviewSummaryService(
        {
            monthlyReview: vi.fn().mockReturnValue(BUILT),
            hash: vi.fn().mockReturnValue(options.hash ?? 'hash-1')
        } as unknown as AiContextBuilderService,
        { generate } as unknown as SummaryGeneratorService,
        { findStored, save } as unknown as AiSummaryDomain,
        { isGranted: vi.fn().mockResolvedValue(options.consent ?? true) } as unknown as AiConsentService,
        { allows: vi.fn().mockResolvedValue(options.allowed ?? true) } as unknown as PlanGateService,
        { get: () => ({ locale: 'pt-BR' }) } as unknown as AppContext,
        metrics as unknown as AiAssistantMetricsService
    );
    return { service, generate, save, findStored, metrics };
}

const INPUT = { review: REVIEW, labels: [] } as const;

describe('MonthlyReviewSummaryService', () => {
    it('sem Premium com a IA ligada não chama o modelo nem guarda nada', async () => {
        const { service, generate, save } = make({ allowed: false });

        expect(await service.paragraphsOf(INPUT)).toBeNull();
        expect(generate).not.toHaveBeenCalled();
        expect(save).not.toHaveBeenCalled();
    });

    it('sem a permissão de envio não chama o modelo', async () => {
        const { service, generate } = make({ consent: false });

        expect(await service.paragraphsOf(INPUT)).toBeNull();
        expect(generate).not.toHaveBeenCalled();
    });

    it('gera, guarda por mês e idioma com o hash do contexto e devolve os parágrafos', async () => {
        const { service, generate, save } = make();

        expect(await service.paragraphsOf(INPUT)).toEqual(['Novo.']);
        expect(generate).toHaveBeenCalledWith(expect.objectContaining({ kind: 'monthly_review', periodKey: '2026-10', locale: 'pt-BR' }));
        expect(save).toHaveBeenCalledWith({
            kind: 'monthly_review',
            periodKey: '2026-10',
            locale: 'pt-BR',
            contextHash: 'hash-1',
            paragraphs: ['Novo.'],
            promptVersion: 1,
            llmCallId: 'call-1',
            auto: true
        });
    });

    it('com o mesmo hash devolve o guardado sem chamar o modelo', async () => {
        const { service, generate, metrics } = make({ stored: STORED });

        expect(await service.paragraphsOf(INPUT)).toEqual(['Guardado.']);
        expect(generate).not.toHaveBeenCalled();
        expect(metrics.summary).toHaveBeenCalledWith('monthly_review', 'cached');
    });

    it('com hash novo gera de novo e regrava', async () => {
        const { service, generate, save } = make({ stored: STORED, hash: 'hash-2' });

        expect(await service.paragraphsOf(INPUT)).toEqual(['Novo.']);
        expect(generate).toHaveBeenCalledTimes(1);
        expect(save).toHaveBeenCalledWith(expect.objectContaining({ contextHash: 'hash-2' }));
    });

    it('cota esgotada devolve o guardado se houver e nada se não houver, contando o motivo', async () => {
        const capped = (): Promise<unknown> => Promise.reject(new CapReachedError('ai', null, 'premium'));
        const withStored = make({ stored: { ...STORED, contextHash: 'old' }, hash: 'hash-2', generate: capped });
        const without = make({ generate: capped });

        expect(await withStored.service.paragraphsOf(INPUT)).toEqual(['Guardado.']);
        expect(await without.service.paragraphsOf(INPUT)).toBeNull();
        expect(without.metrics.summary).toHaveBeenCalledWith('monthly_review', 'cap_reached');
    });

    it('texto reprovado duas vezes pelo guard fica sem parágrafo e sem guardar', async () => {
        const { service, save } = make({ generate: () => Promise.reject(new LlmInvalidResponseError('summary_monthly_review')) });

        expect(await service.paragraphsOf(INPUT)).toBeNull();
        expect(save).not.toHaveBeenCalled();
    });

    it('falha de outro tipo sobe para a fila tentar de novo', async () => {
        const { service } = make({ generate: () => Promise.reject(new Error('provider down')) });

        await expect(service.paragraphsOf(INPUT)).rejects.toThrow('provider down');
    });

    it('lê o guardado do mês e do idioma, e devolve nulo quando não há', async () => {
        expect(await make({ stored: STORED }).service.storedOf('2026-10')).toEqual({
            paragraphs: ['Guardado.'],
            generatedAt: new Date('2026-11-01T05:00:00Z')
        });
        expect(await make().service.storedOf('2026-10')).toBeNull();
    });
});
