import { describe, expect, it, vi } from 'vitest';
import { AppContext } from '../../../core/context/app-context.port';
import { PaidUsageMeter } from '../../../core/usage/services/paid-usage-meter.service';
import { CapReachedError } from '../../../core/usage/usage.errors';
import { AiSummaryDomain } from '../domain/ai-summary.domain';
import { AiAssistantLogService } from '../services/ai-assistant-log.service';
import { AiAssistantMetricsService } from '../services/ai-assistant-metrics.service';
import { AiConsentService } from '../services/ai-consent.service';
import { SummaryGeneratorService } from '../services/summary-generator.service';
import { SummarySubjectService } from '../services/summary-subject.service';
import { SummariesApplication } from './summaries.application';

const CONTEXT = { periodKey: '2026-10:x', contextHash: 'novo', built: {} };

function build(stored: unknown) {
    const generate = vi.fn().mockRejectedValue(new CapReachedError('ai', '2026-12-01T03:00:00.000Z', 'premium'));
    const summary = vi.fn();
    const application: SummariesApplication = new SummariesApplication(
        { of: vi.fn().mockResolvedValue({ mode: 'model', context: CONTEXT }) } as unknown as SummarySubjectService,
        { generate } as unknown as SummaryGeneratorService,
        { findStored: vi.fn().mockResolvedValue(stored) } as unknown as AiSummaryDomain,
        { assertGranted: vi.fn() } as unknown as AiConsentService,
        {
            state: vi.fn().mockResolvedValue({ state: 'paused', usedBps: 10000, resetsAt: '2026-12-01T03:00:00.000Z' })
        } as unknown as PaidUsageMeter,
        { get: () => ({ locale: 'pt-BR' }) } as unknown as AppContext,
        { summaryServed: vi.fn() } as unknown as AiAssistantLogService,
        { summary, summaryRegeneration: vi.fn() } as unknown as AiAssistantMetricsService
    );
    return { application, generate, summary };
}

const STORED = {
    contextHash: 'velho',
    paragraphs: ['Texto guardado.'],
    generatedAt: new Date('2026-11-01T10:00:00Z'),
    lastAutoGeneratedAt: new Date('2026-11-01T10:00:00Z')
};

describe('SummariesApplication com a cota pausada', () => {
    it('leitura: devolve o texto guardado, marcado como velho, sem gerar novo', async () => {
        const { application } = build(STORED);

        const view = await application.get('month', { month: '2026-10' });

        expect(view).toMatchObject({ paragraphs: ['Texto guardado.'], cached: true, stale: true, usage: { state: 'paused' } });
    });

    it('leitura sem texto guardado: segue recusando com 429', async () => {
        const { application } = build(null);

        await expect(application.get('month', { month: '2026-10' })).rejects.toBeInstanceOf(CapReachedError);
    });

    it('escrever de novo: continua bloqueado mesmo com texto guardado', async () => {
        const { application } = build(STORED);

        await expect(application.regenerate('month', { month: '2026-10' })).rejects.toBeInstanceOf(CapReachedError);
    });
});
