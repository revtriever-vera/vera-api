import { Body, Controller, HttpCode, HttpStatus, Param, Post } from '@nestjs/common';
import { ApiOperation, ApiParam, ApiResponse, ApiTags } from '@nestjs/swagger';
import { ApiProblemResponse } from '../../../../core/http/api-problem.decorator';
import { PluggyConnectApplication } from '../../application/pluggy-connect.application';
import { PLUGGY_WEBHOOK_PATH } from '../../domain/bank-connections.types';

@ApiTags('spending')
@Controller(PLUGGY_WEBHOOK_PATH)
export class PluggyWebhookController {
    public constructor(private readonly pluggyConnect: PluggyConnectApplication) {}

    @Post(':token')
    @HttpCode(HttpStatus.OK)
    @ApiOperation({
        summary: 'Receive the Pluggy webhook of a company',
        description:
            'Public route that Pluggy calls at the `webhookUrl` carried by the connect token. The path token is signed by the API and ' +
            'identifies the company. Only `item/created` is acted on: the item is queued and registered later exactly like a pasted ' +
            'Item ID, after checking the `clientId` against the saved credentials and reading the item again at Pluggy. Every other ' +
            'event is acknowledged and ignored. A repeated delivery of the same item does not duplicate the connection.'
    })
    @ApiParam({ name: 'token', description: 'Signed token of the company, generated by the API inside the webhook URL' })
    @ApiResponse({ status: 200, description: 'Acknowledged (queued or ignored)' })
    @ApiProblemResponse({
        status: 401,
        description: 'The path token is not valid (connections.webhook_unauthorized). Pluggy does not retry it',
        example: { type: 'connections.webhook_unauthorized', title: 'WebhookUnauthorizedError', status: 401 }
    })
    public async receive(@Param('token') token: string, @Body() body: unknown): Promise<void> {
        await this.pluggyConnect.receiveWebhook(token, body);
    }
}
